RUNTIME_SLICES = [
    "/* Stkt Dynamic Array / Slice Runtime */",
    "#define STKT_SLICE_DEFINE(TYPE, NAME) \\",
    "typedef struct { TYPE* data; size_t len; size_t cap; } __stkt_slice_buf_##NAME; \\",
    "typedef struct { __stkt_slice_buf_##NAME* buf; } NAME;",
    "STKT_SLICE_DEFINE(int32_t, stkt_slice_i32)",
    "STKT_SLICE_DEFINE(int64_t, stkt_slice_i64)",
    "STKT_SLICE_DEFINE(float, stkt_slice_f32)",
    "STKT_SLICE_DEFINE(double, stkt_slice_f64)",
    "STKT_SLICE_DEFINE(char*, stkt_slice_str)",
    "#define STKT_SLICE_INIT(s) do { \\",
    "    (s).buf = malloc(sizeof(*((s).buf))); \\",
    "    (s).buf->data = NULL; \\",
    "    (s).buf->len = 0; \\",
    "    (s).buf->cap = 0; \\",
    "} while(0)",
    "#define STKT_SLICE_APPEND(s, val) do { \\",
    "    if ((s).buf->len >= (s).buf->cap) { \\",
    "        (s).buf->cap = ((s).buf->cap == 0) ? 4 : ((s).buf->cap * 2); \\",
    "        (s).buf->data = realloc((s).buf->data, (s).buf->cap * sizeof(*((s).buf->data))); \\",
    "    } \\",
    "    (s).buf->data[(s).buf->len++] = (val); \\",
    "} while(0)",
    "#define STKT_SLICE_POP(s) ((s).buf->data[--((s).buf->len)])",
    "#define STKT_SLICE_LEN(s) ((int32_t)((s).buf->len))",
]

RUNTIME_STRINGS = [
    "#include <ctype.h>",
    "/* Stkt String Operations Runtime */",
    "static inline __attribute__((unused)) char* stkt_str_concat(const char* s1, const char* s2) {",
    "    if (!s1) s1 = \"\";",
    "    if (!s2) s2 = \"\";",
    "    size_t len1 = strlen(s1);",
    "    size_t len2 = strlen(s2);",
    "    char* res = (char*)malloc(len1 + len2 + 1);",
    "    if (!res) return \"\";",
    "    memcpy(res, s1, len1);",
    "    memcpy(res + len1, s2, len2);",
    "    res[len1 + len2] = '\\0';",
    "    return res;",
    "}",
    "static inline __attribute__((unused)) char* stkt_str_slice(const char* s, int32_t start, int32_t end) {",
    "    if (!s) return \"\";",
    "    int32_t len = (int32_t)strlen(s);",
    "    if (start < 0) start = 0;",
    "    if (end > len) end = len;",
    "    if (start >= end) { char* empty = (char*)malloc(1); empty[0] = '\\0'; return empty; }",
    "    int32_t sub_len = end - start;",
    "    char* res = (char*)malloc(sub_len + 1);",
    "    if (!res) return \"\";",
    "    memcpy(res, s + start, sub_len);",
    "    res[sub_len] = '\\0';",
    "    return res;",
    "}",
    "static inline __attribute__((unused)) stkt_slice_str stkt_str_split(const char* s, const char* sep) {",
    "    stkt_slice_str res;",
    "    STKT_SLICE_INIT(res);",
    "    if (!s || !sep) return res;",
    "    size_t sep_len = strlen(sep);",
    "    if (sep_len == 0) { STKT_SLICE_APPEND(res, strdup(s)); return res; }",
    "    const char* curr = s;",
    "    const char* found;",
    "    while ((found = strstr(curr, sep)) != NULL) {",
    "        size_t part_len = found - curr;",
    "        char* part = (char*)malloc(part_len + 1);",
    "        memcpy(part, curr, part_len);",
    "        part[part_len] = '\\0';",
    "        STKT_SLICE_APPEND(res, part);",
    "        curr = found + sep_len;",
    "    }",
    "    STKT_SLICE_APPEND(res, strdup(curr));",
    "    return res;",
    "}",
    "static inline __attribute__((unused)) char* stkt_str_trim(const char* s) {",
    "    if (!s) return \"\";",
    "    while (*s && isspace((unsigned char)*s)) s++;",
    "    if (!*s) return strdup(\"\");",
    "    const char* end = s + strlen(s) - 1;",
    "    while (end > s && isspace((unsigned char)*end)) end--;",
    "    size_t len = end - s + 1;",
    "    char* res = (char*)malloc(len + 1);",
    "    memcpy(res, s, len);",
    "    res[len] = '\\0';",
    "    return res;",
    "}",
    "static inline __attribute__((unused)) bool stkt_str_contains(const char* s, const char* sub) {",
    "    if (!s || !sub) return false;",
    "    return strstr(s, sub) != NULL;",
    "}",
]

