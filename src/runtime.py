RUNTIME_HMAP = [
    "/* Stkt Hash Map Runtime */",
    "typedef struct __stkt_map_entry_str_i32 { char* key; int32_t val; struct __stkt_map_entry_str_i32* next; } __stkt_map_entry_str_i32;",
    "typedef struct { __stkt_map_entry_str_i32* buckets[64]; int32_t size; } __stkt_map_str_i32;",
    "static inline __attribute__((unused)) uint32_t __stkt_hash_str(const char* s) {",
    "    uint32_t h = 2166136261u; if (!s) return 0; while (*s) { h ^= (uint8_t)*s++; h *= 16777619u; } return h;",
    "}",
    "static inline __attribute__((unused)) __stkt_map_str_i32* __stkt_map_create_str_i32() {",
    "    return (__stkt_map_str_i32*)calloc(1, sizeof(__stkt_map_str_i32));",
    "}",
    "static inline __attribute__((unused)) void __stkt_map_set_str_i32(__stkt_map_str_i32* m, const char* key, int32_t val) {",
    "    if (!m || !key) return;",
    "    uint32_t idx = __stkt_hash_str(key) % 64;",
    "    __stkt_map_entry_str_i32* curr = m->buckets[idx];",
    "    while (curr) { if (strcmp(curr->key, key) == 0) { curr->val = val; return; } curr = curr->next; }",
    "    __stkt_map_entry_str_i32* entry = (__stkt_map_entry_str_i32*)malloc(sizeof(__stkt_map_entry_str_i32));",
    "    entry->key = strdup(key); entry->val = val; entry->next = m->buckets[idx]; m->buckets[idx] = entry; m->size++;",
    "}",
    "static inline __attribute__((unused)) int32_t __stkt_map_get_str_i32(__stkt_map_str_i32* m, const char* key) {",
    "    if (!m || !key) { __stkt_set_err(); return 0; }",
    "    uint32_t idx = __stkt_hash_str(key) % 64;",
    "    __stkt_map_entry_str_i32* curr = m->buckets[idx];",
    "    while (curr) { if (strcmp(curr->key, key) == 0) { return curr->val; } curr = curr->next; }",
    "    __stkt_set_err(); return 0;",
    "}",
    "static inline __attribute__((unused)) bool __stkt_map_has_str_i32(__stkt_map_str_i32* m, const char* key) {",
    "    if (!m || !key) return false;",
    "    uint32_t idx = __stkt_hash_str(key) % 64;",
    "    __stkt_map_entry_str_i32* curr = m->buckets[idx];",
    "    while (curr) { if (strcmp(curr->key, key) == 0) return true; curr = curr->next; }",
    "    return false;",
    "}",
    "static inline __attribute__((unused)) stkt_slice_str __stkt_map_keys_str_i32(__stkt_map_str_i32* m) {",
    "    stkt_slice_str res; STKT_SLICE_INIT(res); if (!m) return res;",
    "    for (int i = 0; i < 64; i++) {",
    "        __stkt_map_entry_str_i32* curr = m->buckets[i];",
    "        while (curr) { STKT_SLICE_APPEND(res, curr->key); curr = curr->next; }",
    "    }",
    "    return res;",
    "}",
]

